-- Não toca na tabela baileys_auth nem em qualquer sessão existente.
create table if not exists public.app_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default '',
  assistant_name text not null default 'Nuvem',
  language text not null default 'pt-BR',
  response_style text not null default 'balanced',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table if not exists public.app_chat_messages (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null check (role in ('user','assistant')),
  content text not null check (char_length(content) between 1 and 12000),
  created_at timestamptz not null default now()
);
create index if not exists app_chat_messages_user_created_idx on public.app_chat_messages(user_id, created_at desc);
create table if not exists public.app_expenses (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  description text not null check (char_length(description) between 1 and 160),
  amount numeric(12,2) not null check (amount > 0 and amount <= 100000000),
  category text not null default 'Outros' check (char_length(category) between 1 and 60),
  spent_at date not null default current_date,
  created_at timestamptz not null default now()
);
create index if not exists app_expenses_user_spent_idx on public.app_expenses(user_id, spent_at desc);

alter table public.app_profiles enable row level security;
alter table public.app_chat_messages enable row level security;
alter table public.app_expenses enable row level security;

drop policy if exists "app_profiles_own_rows" on public.app_profiles;
create policy "app_profiles_own_rows" on public.app_profiles for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
drop policy if exists "app_chat_own_rows" on public.app_chat_messages;
create policy "app_chat_own_rows" on public.app_chat_messages for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
drop policy if exists "app_expenses_own_rows" on public.app_expenses;
create policy "app_expenses_own_rows" on public.app_expenses for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
