-- Nuvem Life: private workout and meal logs.
-- This migration adds new tables only and does not modify existing accounts or WhatsApp sessions.
create table if not exists public.app_wellness_records (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  record_type text not null check (record_type in ('workout', 'meal')),
  title text not null check (char_length(title) between 1 and 120),
  entry_date date not null default current_date,
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  constraint app_wellness_payload_object check (jsonb_typeof(payload) = 'object')
);
create index if not exists app_wellness_user_type_date_idx
  on public.app_wellness_records(user_id, record_type, entry_date desc, created_at desc);
alter table public.app_wellness_records enable row level security;
drop policy if exists app_wellness_select_own on public.app_wellness_records;
create policy app_wellness_select_own on public.app_wellness_records
  for select to authenticated using (auth.uid() = user_id);
drop policy if exists app_wellness_insert_own on public.app_wellness_records;
create policy app_wellness_insert_own on public.app_wellness_records
  for insert to authenticated with check (auth.uid() = user_id);
drop policy if exists app_wellness_update_own on public.app_wellness_records;
create policy app_wellness_update_own on public.app_wellness_records
  for update to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
drop policy if exists app_wellness_delete_own on public.app_wellness_records;
create policy app_wellness_delete_own on public.app_wellness_records
  for delete to authenticated using (auth.uid() = user_id);
