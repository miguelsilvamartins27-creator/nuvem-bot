-- Nuvem: lembretes pessoais. Não altera tabelas nem sessão do WhatsApp.
create table if not exists public.app_reminders (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null check (char_length(title) between 1 and 120),
  note text not null default '' check (char_length(note) <= 240),
  remind_at time not null,
  repeat_daily boolean not null default true,
  remind_date date,
  active boolean not null default true,
  last_notified_at timestamptz,
  created_at timestamptz not null default now(),
  constraint app_reminders_date_rule check (repeat_daily or remind_date is not null)
);
create index if not exists app_reminders_user_created_idx on public.app_reminders(user_id, created_at desc);
create index if not exists app_reminders_active_time_idx on public.app_reminders(active, remind_at);
alter table public.app_reminders enable row level security;
drop policy if exists app_reminders_select_own on public.app_reminders;
create policy app_reminders_select_own on public.app_reminders for select to authenticated using (auth.uid() = user_id);
drop policy if exists app_reminders_insert_own on public.app_reminders;
create policy app_reminders_insert_own on public.app_reminders for insert to authenticated with check (auth.uid() = user_id);
drop policy if exists app_reminders_update_own on public.app_reminders;
create policy app_reminders_update_own on public.app_reminders for update to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
drop policy if exists app_reminders_delete_own on public.app_reminders;
create policy app_reminders_delete_own on public.app_reminders for delete to authenticated using (auth.uid() = user_id);
