-- Nuvem: inscrições de Web Push e fuso horário para lembretes.
-- Não altera nem remove dados da sessão do WhatsApp.
alter table public.app_reminders
  add column if not exists timezone text not null default 'America/Sao_Paulo';

create table if not exists public.app_push_subscriptions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  endpoint text not null unique,
  subscription jsonb not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists app_push_subscriptions_user_idx
  on public.app_push_subscriptions(user_id);

alter table public.app_push_subscriptions enable row level security;
drop policy if exists app_push_subscriptions_select_own on public.app_push_subscriptions;
create policy app_push_subscriptions_select_own on public.app_push_subscriptions
  for select to authenticated using (auth.uid() = user_id);
drop policy if exists app_push_subscriptions_insert_own on public.app_push_subscriptions;
create policy app_push_subscriptions_insert_own on public.app_push_subscriptions
  for insert to authenticated with check (auth.uid() = user_id);
drop policy if exists app_push_subscriptions_update_own on public.app_push_subscriptions;
create policy app_push_subscriptions_update_own on public.app_push_subscriptions
  for update to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
drop policy if exists app_push_subscriptions_delete_own on public.app_push_subscriptions;
create policy app_push_subscriptions_delete_own on public.app_push_subscriptions
  for delete to authenticated using (auth.uid() = user_id);
